export function getResource(id) {
  return resources.find((r) => r.id === id)
}

export function filterResources(category) {
  if (!category || category === 'all') return resources
  return resources.filter((r) => r.categories?.includes(category))
}

export const featuredResources = resources.filter((r) => r.featured && !r.comingSoon).slice(0, 3)
